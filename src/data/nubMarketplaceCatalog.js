export function getNubMarketplaceCategory(name) {
  return NUB_MARKETPLACE_CATEGORIES.find((category) => category.name === name) || null;
}

export function getRecommendedProgramsForListing(categoryName, subcategoryName = '') {
  const category = getNubMarketplaceCategory(categoryName);
  if (!category) return { allPrograms: false, programCodes: [] };
  if (category.allPrograms) return { allPrograms: true, programCodes: [] };
  if (category.name === 'Academic Projects' && ACADEMIC_PROJECT_RECOMMENDATIONS[subcategoryName]) {
    return { allPrograms: false, programCodes: [...ACADEMIC_PROJECT_RECOMMENDATIONS[subcategoryName]] };
  }
  return { allPrograms: false, programCodes: [...category.recommendedProgramCodes] };
}

export function isAcademicProjectCategory(categoryName) {
  return categoryName === 'Academic Projects';
}
