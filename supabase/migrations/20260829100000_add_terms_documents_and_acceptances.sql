create or replace function public.publish_terms_document(
  requested_title text,
  requested_file_name text,
  requested_storage_path text,
  requested_extracted_text text,
  requested_content_hash text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  next_version integer;
  published_id uuid;
begin
  if not exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and lower(p.role::text) = 'admin'
  ) then
    raise exception 'Administrator access is required.';
  end if;

  if length(trim(coalesce(requested_title, ''))) < 3
     or length(trim(coalesce(requested_file_name, ''))) < 5
     or length(trim(coalesce(requested_storage_path, ''))) < 5
     or length(trim(coalesce(requested_extracted_text, ''))) < 50 then
    raise exception 'A title, PDF file, storage path, and extracted terms text are required.';
  end if;

  perform pg_advisory_xact_lock(hashtext('borrowkoto:publish-terms'));
  select coalesce(max(version), 0) + 1 into next_version from public.terms_documents;
  update public.terms_documents set is_active = false where is_active;

  insert into public.terms_documents (
    title,
    version,
    file_name,
    storage_path,
    extracted_text,
    content_hash,
    is_active,
    published_by,
    published_at
  ) values (
    trim(requested_title),
    next_version,
    trim(requested_file_name),
    trim(requested_storage_path),
    trim(requested_extracted_text),
    nullif(trim(coalesce(requested_content_hash, '')), ''),
    true,
    auth.uid(),
    now()
  ) returning id into published_id;

  return published_id;
end;
$$;

revoke all on function public.publish_terms_document(text, text, text, text, text) from public;
grant execute on function public.publish_terms_document(text, text, text, text, text) to authenticated;

