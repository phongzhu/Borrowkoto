create table if not exists public.terms_documents (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  version integer not null unique check (version > 0),
  file_name text not null,
  storage_path text not null unique,
  extracted_text text not null check (length(trim(extracted_text)) >= 50),
  content_hash text,
  is_active boolean not null default false,
  published_by uuid references auth.users(id) on delete set null,
  published_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create unique index if not exists terms_documents_one_active_idx
  on public.terms_documents (is_active)
  where is_active;

create table if not exists public.terms_acceptances (
  id bigint generated by default as identity primary key,
  terms_document_id uuid not null references public.terms_documents(id) on delete restrict,
  user_id uuid not null references auth.users(id) on delete cascade,
  acceptance_context text not null check (acceptance_context in ('activation', 'checkout')),
  item_id uuid references public.items(id) on delete set null,
  booking_id uuid references public.bookings(id) on delete set null,
  accepted_at timestamptz not null default now(),
  user_agent text
);

create index if not exists terms_acceptances_user_idx
  on public.terms_acceptances (user_id, accepted_at desc);

create index if not exists terms_acceptances_document_idx
  on public.terms_acceptances (terms_document_id, accepted_at desc);

alter table public.terms_documents enable row level security;
alter table public.terms_acceptances enable row level security;

